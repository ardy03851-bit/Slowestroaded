// Convert the bundled Quaternius GLB to the game's native OBJ format.
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";

const file = readFileSync(new URL("assets/quaternius-sports-car.glb", import.meta.url));
assert.equal(file.toString("ascii", 0, 4), "glTF");
assert.equal(file.readUInt32LE(4), 2);
const jsonEnd = 20 + file.readUInt32LE(12);
const model = JSON.parse(file.toString("utf8", 20, jsonEnd));
const binary = file.subarray(jsonEnd + 8);
const materialKeys = {
  White: "sportBody",
  Windows: "sportGlass",
  Grey: "sportTrim",
  Headlights: "sportHead",
  TailLights: "sportTail",
  Black: "sportTyre",
};

function accessor(index, width) {
  const { bufferView, byteOffset = 0, count, componentType } = model.accessors[index];
  const { byteOffset: start = 0, byteStride } = model.bufferViews[bufferView];
  const types = { 5121: [1, "readUInt8"], 5123: [2, "readUInt16LE"], 5125: [4, "readUInt32LE"], 5126: [4, "readFloatLE"] };
  const [size, read] = types[componentType];
  return Array.from({ length: count }, (_, i) =>
    Array.from({ length: width }, (_, j) =>
      binary[read](start + byteOffset + i * (byteStride ?? size * width) + j * size)
    )
  );
}

const meshes = Object.fromEntries(model.nodes.map(({ name, mesh }) => [
  name.split(".")[0].split("_").slice(0, 2).join("_"),
  model.meshes[mesh].primitives.map(({ attributes, indices, material, mode = 4 }) => {
    assert.equal(mode, 4);
    return {
      positions: accessor(attributes.POSITION, 3),
      normals: accessor(attributes.NORMAL, 3),
      faces: accessor(indices, 1).flat(),
      material: materialKeys[model.materials[material].name],
    };
  }),
]));

// The game origin is at the rear axle on the ground. Its OBJ body loader
// rotates by -90 degrees around Y, so pre-rotate the +Z-forward GLB by +90.
const ground = -0.015738;
const rearZ = -1.320760;
const frontZ = 1.185924;
const wheelY = 0.264656;
const halfTrack = 0.725043;
const centerX = 0.0009485;
const body = meshes.SportsCar2_Cube.map(part => ({
  ...part,
  name: "body",
  point: ([x, y, z]) => [z - rearZ, y - ground, -(x - centerX)],
  normal: ([x, y, z]) => [z, y, -x],
}));

const wheels = [];
for (const [name, source, side, axle] of [
  ["fl", "FrontLeftWheel", 1, frontZ],
  ["fr", "FrontRightWheel", -1, frontZ],
  ["rl", "BackWheels", 1, rearZ],
  ["rr", "BackWheels", -1, rearZ],
]) {
  for (const part of meshes[`SportsCar2_${source}`]) {
    const faces = [];
    for (let i = 0; i < part.faces.length; i += 3) {
      const triangle = part.faces.slice(i, i + 3);
      if (source !== "BackWheels" || triangle.every(v => part.positions[v][0] * side > 0)) {
        faces.push(...triangle);
      }
    }
    // Store each wheel about its own pivot, before the game's +/-90° rotation.
    wheels.push({
      ...part, faces, name,
      point: ([x, y, z]) => [-side * (z - axle), y - wheelY, side * (x - centerX) - halfTrack],
      normal: ([x, y, z]) => [-side * z, y, side * x],
    });
  }
}

function writeObj(filename, parts) {
  let offset = 1;
  const lines = ["# Quaternius Sports Car (CC0); generated by tools/convert-sports-car.mjs"];
  for (const { positions, normals, faces, material, name, point, normal } of parts) {
    assert.ok(material && faces.length);
    lines.push(`o ${name}_${material}`);
    const indices = new Map();
    for (const index of new Set(faces)) {
      indices.set(index, offset++);
      lines.push(`v ${point(positions[index]).map(n => n.toFixed(6)).join(" ")}`);
      lines.push(`vn ${normal(normals[index]).map(n => n.toFixed(6)).join(" ")}`);
    }
    for (let i = 0; i < faces.length; i += 3) {
      lines.push(`f ${faces.slice(i, i + 3).map(v => {
        const n = indices.get(v);
        return `${n}//${n}`;
      }).join(" ")}`);
    }
  }
  writeFileSync(new URL(`../static/media/${filename}`, import.meta.url), lines.join("\n") + "\n");
}

writeObj("quaternius-sports-car-body.obj", body);
writeObj("quaternius-sports-car-wheels.obj", wheels);
